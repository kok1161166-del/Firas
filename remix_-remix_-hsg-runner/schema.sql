-- HSG Runner - Supabase Database Schema
-- Copy and paste this into the Supabase SQL Editor

-- 1. Create rooms table
CREATE TABLE IF NOT EXISTS rooms (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at TIMESTAMPTZ DEFAULT now(),
  host_id TEXT NOT NULL,
  mode TEXT NOT NULL CHECK (mode IN ('PUBLIC', 'PRIVATE')),
  status TEXT NOT NULL DEFAULT 'LOBBY' CHECK (status IN ('LOBBY', 'PLAYING', 'FINISHED')),
  player_count INTEGER DEFAULT 1,
  short_id TEXT UNIQUE NOT NULL,
  start_time TIMESTAMPTZ,
  map_id INTEGER DEFAULT 1
);

-- 2. Create players table
CREATE TABLE IF NOT EXISTS players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT now(),
  room_id UUID REFERENCES rooms(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  is_ready BOOLEAN DEFAULT false,
  last_seen TIMESTAMPTZ DEFAULT now(),
  distance INTEGER DEFAULT 0,
  score INTEGER DEFAULT 0,
  is_dead BOOLEAN DEFAULT false,
  is_finished BOOLEAN DEFAULT false,
  lane INTEGER DEFAULT 0,
  y FLOAT DEFAULT 0,
  z FLOAT DEFAULT 0,
  UNIQUE(room_id, user_id)
);

-- 3. Create global leaderboard table (Optional but recommended)
CREATE TABLE IF NOT EXISTS global_leaderboard (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ DEFAULT now(),
  user_id TEXT NOT NULL,
  name TEXT NOT NULL,
  score INTEGER NOT NULL,
  distance INTEGER NOT NULL
);

-- 4. Create profiles table
CREATE TABLE IF NOT EXISTS profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  username TEXT NOT NULL,
  avatar_url TEXT,
  points INTEGER DEFAULT 0,
  current_level INTEGER DEFAULT 1,
  current_map INTEGER DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT now(),
  updated_at TIMESTAMPTZ DEFAULT now()
);

-- 5. Create inventory table
CREATE TABLE IF NOT EXISTS inventory (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id UUID REFERENCES profiles(id) ON DELETE CASCADE,
  item_id TEXT NOT NULL,
  item_type TEXT NOT NULL,
  purchased_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(user_id, item_id)
);

-- 6. Enable Realtime for these tables
-- Note: You might need to do this manually in the Supabase Dashboard under Database -> Replication
-- but these commands attempt to do it via SQL.
BEGIN;
  DROP PUBLICATION IF EXISTS supabase_realtime;
  CREATE PUBLICATION supabase_realtime;
COMMIT;
ALTER PUBLICATION supabase_realtime ADD TABLE rooms;
ALTER PUBLICATION supabase_realtime ADD TABLE players;
ALTER PUBLICATION supabase_realtime ADD TABLE global_leaderboard;
ALTER PUBLICATION supabase_realtime ADD TABLE profiles;
ALTER PUBLICATION supabase_realtime ADD TABLE inventory;

-- 7. Enable Row Level Security (RLS)
ALTER TABLE rooms ENABLE ROW LEVEL SECURITY;
ALTER TABLE players ENABLE ROW LEVEL SECURITY;
ALTER TABLE global_leaderboard ENABLE ROW LEVEL SECURITY;
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE inventory ENABLE ROW LEVEL SECURITY;

