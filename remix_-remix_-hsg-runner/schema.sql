-- 8. Create permissive policies (Allow anyone to read/write for the game)
-- In a production app, you would restrict these more.
DROP POLICY IF EXISTS "Public Rooms Access" ON rooms;
CREATE POLICY "Public Rooms Access" ON rooms FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public Players Access" ON players;
CREATE POLICY "Public Players Access" ON players FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public Leaderboard Access" ON global_leaderboard;
CREATE POLICY "Public Leaderboard Access" ON global_leaderboard FOR ALL USING (true) WITH CHECK (true);

-- Profiles policies
DROP POLICY IF EXISTS "Public profiles are viewable by everyone." ON profiles;
CREATE POLICY "Public profiles are viewable by everyone." ON profiles FOR SELECT USING (true);

DROP POLICY IF EXISTS "Users can insert their own profile." ON profiles;
CREATE POLICY "Users can insert their own profile." ON profiles FOR INSERT WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update own profile." ON profiles;
CREATE POLICY "Users can update own profile." ON profiles FOR UPDATE USING (auth.uid() = id);

-- Inventory policies
DROP POLICY IF EXISTS "Public inventory is viewable by everyone." ON inventory;
CREATE POLICY "Public inventory is viewable by everyone." ON inventory FOR SELECT USING (true);

DROP POLICY IF EXISTS "Users can insert their own inventory." ON inventory;
CREATE POLICY "Users can insert their own inventory." ON inventory FOR INSERT WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can update own inventory." ON inventory;
CREATE POLICY "Users can update own inventory." ON inventory FOR UPDATE USING (auth.uid() = user_id);

